///
/// **This file is the only thing outside `docs/` this linter knows about, and
/// it is inside `docs/`.** Seven checks used to open `crates/**` and `demo/**`
/// and re-derive in JavaScript, with regexes, what that crate derives in Rust
/// with `syn` and `toml_edit` — two implementations of one definition, which is
/// how the landing came to claim 28 capabilities against a linter that counted
/// 27 while this file's own comment said the two could not disagree.
///
/// Reading instead of deriving buys three things at once. The definition has
/// one home. The job's `paths: docs/**` filter becomes a *true* declaration of
/// its input set, where before it named one class of eight. And a framework
/// change that moves a fact regenerates this file, so the commit that falsifies
/// a page is the commit that trips the gate — rather than the next unrelated
/// docs edit, named as the culprit.
///
/// Staleness is the join's business, not this file's: checking would mean
/// reading `crates/`, which is the property being bought. `cargo nextest run -p
/// nest-rs-conformance` rewrites this and fails until it is committed.
