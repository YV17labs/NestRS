function loadArtefact(name) {
  try {
    return JSON.parse(readFileSync(join(DOCS_ROOT, name), 'utf8'));
  } catch (cause) {
    throw new Error(`cannot read docs/${name} (${cause.message}) — it is generated by `
      + '`cargo nextest run -p nest-rs-conformance`, which writes it and fails until it is '
      + 'committed');
  }
}

function loadCanon() {
  const path = join(DOCS_ROOT, 'canon.json');
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(path, 'utf8'));
  } catch (cause) {
    throw new Error(`cannot read docs/canon.json (${cause.message}) — it is generated by `
      + '`cargo nextest run -p nest-rs-conformance`, which writes it and fails until it is '
      + 'committed. Every code-truth check reads it; none of them can run without it.');
  }
  // Fail closed on a truncated or half-written canon: a missing key would
  // silently disable whichever checks read it, which is the failure mode every
  // derivation in this file already throws to avoid.
  const owed = [
    'capabilities', 'decorators', 'layer_subtraits', 'trait_methods', 'test_count',
    'version_req', 'otel_binding', 'envelope_keys', 'configs', 'architecture',
  ];
  const missing = owed.filter((key) => parsed[key] === undefined);
  if (missing.length) {
    throw new Error(`docs/canon.json is missing ${missing.join(', ')} — regenerate it with `
      + '`cargo nextest run -p nest-rs-conformance`, do not hand-edit it');
  }
  return parsed;
}

